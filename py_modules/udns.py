import ipaddress
import json
import os
import shutil

import decky

from resolved import systemctl

# 127.bu.zz.1e :xdd:
LISTEN = "127.28.99.13:5053"
UNIT = "decky-dot-dns-udns.service"
UNIT_PATH = f"/etc/systemd/system/{UNIT}"
PLUGIN_BINARY = os.path.join(decky.DECKY_PLUGIN_DIR, "bin", "udns")
DATA_DIR = "/var/lib/decky-dot-dns"
BINARY = os.path.join(DATA_DIR, "udns")
CONFIG_PATH = os.path.join(DATA_DIR, "udns.toml")


def upstream(ip: str, host: str, protocol: str) -> str:
    # host may carry a path (e.g. dns.nextdns.io/abc123), defaulting to /dns-query
    name, _, path = host.partition("/")
    if not name:
        raise ValueError(f"upstream {ip} needs a hostname")
    addr = ipaddress.ip_address(ip)
    port = 443 if protocol == "https" else 853
    sock = f"[{addr}]:{port}" if addr.version == 6 else f"{addr}:{port}"
    config = f"""[[upstream.servers]]
protocol = "{protocol}"
addr = "{sock}"
server_name = {json.dumps(name)}
"""
    if protocol == "https":
        config += f"path = {json.dumps('/' + (path or 'dns-query'))}\n"
    return config


def make_config(servers: list[tuple[str, str]], protocol: str) -> str:
    upstreams = "\n".join(upstream(ip, host, protocol) for ip, host in servers if ip)
    if not upstreams:
        raise ValueError("udns needs at least one upstream")
    return f"""# Generated by decky-dot-dns
{upstreams}
[dns]
enabled = true
listen = ["{LISTEN}"]
"""


def start(servers: list[tuple[str, str]], protocol: str):
    config = make_config(servers, protocol)
    os.makedirs(DATA_DIR, mode=0o755, exist_ok=True)
    shutil.copyfile(PLUGIN_BINARY, BINARY + ".new")
    os.chmod(BINARY + ".new", 0o755)
    os.replace(BINARY + ".new", BINARY)
    with open(CONFIG_PATH, "w") as f:
        f.write(config)
    os.chmod(CONFIG_PATH, 0o644)
    with open(UNIT_PATH, "w") as f:
        f.write(f"""# Generated by decky-dot-dns
[Unit]
Description=udns forwarder - decky-dot-dns

[Service]
ExecStart={BINARY} {CONFIG_PATH}
Restart=on-failure
# Throw away basically everything. We need none.
DynamicUser=yes
CapabilityBoundingSet=
AmbientCapabilities=
NoNewPrivileges=yes
PrivateUsers=yes
PrivateDevices=yes
PrivateTmp=yes
ProtectSystem=strict
ProtectHome=yes
ProtectProc=invisible
ProcSubset=pid
ProtectClock=yes
ProtectHostname=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
RestrictAddressFamilies=AF_INET AF_INET6
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
SystemCallArchitectures=native
SystemCallFilter=@system-service
SystemCallFilter=~@privileged
UMask=0077

[Install]
WantedBy=multi-user.target
""")
    systemctl("daemon-reload", check=True)
    systemctl("enable", UNIT, check=True)
    systemctl("restart", UNIT, check=True)


def stop():
    if os.path.exists(UNIT_PATH):
        systemctl("disable", "--now", UNIT)
        os.remove(UNIT_PATH)
        systemctl("daemon-reload")
